def build_curated_learning_plan() -> dict:
    sources = seed_candidate_sources()
    taxonomy = canonical_taxonomy()
    contrast = cross_source_contrast_matrix()
    cap_map = brain_coding_capability_map()
    accepted = [s for s in sources if s["acceptance_status"] == "accept"]
    hold = [s for s in sources if s["acceptance_status"] == "hold"]
    rejected = [s for s in sources if s["acceptance_status"] == "reject"]
    return {
        "front_id": front_id(),
        "domain": learning_domain(),
        "taxonomy": taxonomy,
        "acceptance_criteria": source_acceptance_criteria(),
        "rejection_criteria": source_rejection_criteria(),
        "safety_rubric": source_safety_scoring_rubric(),
        "contrast_rubric": source_contrast_scoring_rubric(),
        "brain_coding_capability_map": cap_map,
        "sources": sources,
        "cross_source_contrast_matrix": contrast,
        "knowledge_record_schema": knowledge_record_schema(),
        "summary": {
            "source_count": len(sources),
            "taxonomy_count": len(taxonomy),
            "capability_map_count": len(cap_map),
            "source_groups": list({s["source_group"] for s in sources}),
            "accepted_count": len(accepted),
            "hold_count": len(hold),
            "rejected_count": len(rejected),
            "ingestion_status": "dry_run_only",
            "memory_mutated": False,
            "faiss_mutated": False,
        },
    }


