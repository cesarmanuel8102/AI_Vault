def assert_no_memory_or_faiss_mutation(before: dict, after: dict) -> dict:
    """Compare before/after inventory dicts. Returns pass/fail details."""
    checks = {
        "semantic_memory_jsonl_sha": before.get("semantic_memory_jsonl", {}).get("sha256") == after.get("semantic_memory_jsonl", {}).get("sha256"),
        "semantic_memory_jsonl_lines": before.get("semantic_memory_jsonl", {}).get("line_count") == after.get("semantic_memory_jsonl", {}).get("line_count"),
        "faiss_index_sha": before.get("semantic_memory_faiss_index", {}).get("sha256") == after.get("semantic_memory_faiss_index", {}).get("sha256"),
        "faiss_ids_sha": before.get("semantic_memory_faiss_ids", {}).get("sha256") == after.get("semantic_memory_faiss_ids", {}).get("sha256"),
        "faiss_ids_count": before.get("semantic_memory_faiss_ids", {}).get("id_count") == after.get("semantic_memory_faiss_ids", {}).get("id_count"),
    }
    all_pass = all(checks.values())
    return {
        "pass": all_pass,
        "checks": checks,
        "before_summary": {k: before.get(k, {}).get("sha256", before.get(k, {}).get("line_count", before.get(k, {}).get("id_count"))) for k in before if k not in ("timestamp", "head")},
        "after_summary": {k: after.get(k, {}).get("sha256", after.get(k, {}).get("line_count", after.get(k, {}).get("id_count"))) for k in after if k not in ("timestamp", "head")},
    }
